#!/usr/bin/env python3
"""Generate the stdcall adapters that connect recompiled x86 code to the native shim.

The shim in runtime/shim is the only Win32 implementation. Its functions take plain C
arguments. This script reads the shim's WINAPI prototypes, and for each function that
is both declared and defined it writes an adapter. The adapter reads the arguments
from the guest stack, calls the shim, and pops the stdcall argument bytes.

Usage: gen_adapters.py SHIM_ROOT OUT.c

Functions declared but not defined get no adapter. An import with no adapter traps
at run time with its name. The list of such functions is printed.
"""
import glob
import os
import re
import sys

WIDE64 = {'LONGLONG', 'ULONGLONG', 'DWORD64', 'INT64', 'UINT64'}
RET_64 = WIDE64


def strip_comments(text):
    text = re.sub(r'/\*.*?\*/', ' ', text, flags=re.S)
    return re.sub(r'//[^\n]*', ' ', text)


def parse_params(plist):
    plist = plist.strip()
    if plist in ('', 'void'):
        return []
    out = []
    for raw in plist.split(','):
        raw = raw.strip()
        m = re.match(r'^(.*?)([A-Za-z_][A-Za-z0-9_]*)$', raw)
        if not m:
            raise ValueError(f"cannot parse parameter {raw!r}")
        ctype = m.group(1).strip()
        if not ctype:
            ctype = m.group(2)  # unnamed parameter
        out.append(ctype.replace('const', '').strip())
    return out


def slots_for(ctype):
    if '*' in ctype:
        return 1
    base = ctype.split()[-1] if ctype.split() else ctype
    if base in WIDE64:
        return 2
    if base in ('float', 'double'):
        raise ValueError(f"floating-point argument {ctype} is not supported by the stdcall adapter")
    return 1


def load_prototypes(shim_root):
    protos = {}
    for path in sorted(glob.glob(os.path.join(shim_root, 'include', 'win32', '*.h'))):
        text = strip_comments(open(path, errors='replace').read())
        for m in re.finditer(r'([A-Za-z_][\w \t\*]*?)\bWINAPI\s+([A-Za-z_]\w*)\s*\(([^;{)]*)\)\s*;', text):
            ret, name, params = m.group(1).strip(), m.group(2), m.group(3)
            protos.setdefault(name, (ret, parse_params(params), os.path.basename(path)))
    return protos


def load_definitions(shim_root):
    defined = set()
    for path in glob.glob(os.path.join(shim_root, 'src', '*.c')):
        text = strip_comments(open(path, errors='replace').read())
        for m in re.finditer(r'\bWINAPI\s+([A-Za-z_]\w*)\s*\([^;{]*\)\s*\{', text):
            defined.add(m.group(1))
    return defined


def emit(protos, names):
    headers = sorted({protos[n][2] for n in names})
    out = [
        "/* Generated by tools/recomp/rt/gen_adapters.py from runtime/shim. Do not edit. */",
        '#include "vt3rt.h"',
    ] + [f'#include "win32/{h}"' for h in headers] + [
        "",
        "#define VT_ARG(c, i) rd32((c)->esp + 4u + 4u * (uint32_t)(i))",
        "",
    ]
    table = []
    for name in names:
        ret, params, _ = protos[name]
        slot_counts = [slots_for(p) for p in params]
        nslots = sum(slot_counts)
        out.append(f"static void imp_{name}(vt3_cpu *c)")
        out.append("{")
        idx = 0
        args = []
        for p, n in zip(params, slot_counts):
            if n == 1:
                out.append(f"    uint32_t a{idx} = VT_ARG(c, {idx});")
                args.append(f"({p})a{idx}")
                idx += 1
            else:
                out.append(f"    uint64_t a{idx} = ((uint64_t)VT_ARG(c, {idx + 1}) << 32) | VT_ARG(c, {idx});")
                args.append(f"({p})a{idx}")
                idx += 2
        call = f"{name}({', '.join(args)})"
        base_ret = ret.split()[-1] if ret.split() else ret
        if ret == 'void':
            out.append(f"    {call};")
        elif base_ret in RET_64 or ret.startswith(('LONGLONG', 'ULONGLONG')):
            out.append(f"    uint64_t r = (uint64_t){call};")
            out.append("    c->eax = (uint32_t)r;")
            out.append("    c->edx = (uint32_t)(r >> 32);")
        else:
            out.append(f"    c->eax = (uint32_t)({call});")
        out.append(f"    c->esp += 4u + {4 * nslots}u;")
        out.append("}")
        out.append("")
        table.append(f'    {{"{name}", imp_{name}}},')
    out.append("const vt3_shim_entry vt3_shim_table[] = {")
    out.extend(table)
    out.append("    {0, 0},")
    out.append("};")
    out.append(f"const size_t vt3_shim_count = {len(names)};")
    out.append("")
    return "\n".join(out)


def main(argv):
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    shim_root, out_path = argv[1], argv[2]
    protos = load_prototypes(shim_root)
    defined = load_definitions(shim_root)
    names = sorted(n for n in protos if n in defined)
    missing = sorted(n for n in protos if n not in defined)
    with open(out_path, 'w') as f:
        f.write(emit(protos, names))
    print(f"adapters: {len(names)} (declared {len(protos)}, defined {len(defined)})")
    if missing:
        print("declared but not implemented:", " ".join(missing))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
