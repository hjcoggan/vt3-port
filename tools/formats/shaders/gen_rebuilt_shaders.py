#!/usr/bin/env python3
"""Writes runtime/shim/src/d3dx9_rebuilt.c: the bytecode for HLSL the game compiles at run time.

VT3.exe calls D3DXCompileShader on four small sources that no shipped blob covers. The runtime's
HLSL subset compiler refuses them (register globals, out parameters, length, saturate). Each
source is rebuilt here as SM2 assembly that does the same arithmetic, written against the
column-major matrix layout the game's own transform shaders use (mul then mad over c0..c3). Each
rebuilt blob carries a CTAB comment with the source's constants, so the constant table works.

The table key is the source's address in the game image, its length, its entry point and its
profile kind, as in the shipped-blob table in d3dx9_stub.c. Run this script after editing a listing.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import sm2_asm  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
OUT = os.path.join(ROOT, "runtime", "shim", "src", "d3dx9_rebuilt.c")

# (name, source address, source length, entry, kind, constants, listing). The HLSL is kept in the
# comment above each entry so the listing can be checked against it.
SHADERS = [
    # float4 g_colour : register(c0); float4 g_lightVec : register(c1);
    # float4 main() : COLOR { return g_colour; }
    ("colour_ps", 0x006CFF58, 111, "main", "p",
     [("g_colour", 2, 0, 1), ("g_lightVec", 2, 1, 1)],
     """ps_2_0
mov oC0, c0
"""),
    # float4 g_colour : register(c0);
    # float4 main(float4 normal : TEXCOORD0) : COLOR { return float4(g_colour.xyz * normal.w, 1); }
    ("normal_ps", 0x006CFED8, 126, "main", "p",
     [("g_colour", 2, 0, 1)],
     """ps_2_0
dcl_texcoord0 t0
def c1, 1, 1, 1, 1
mul r0.xyz, c0, t0.wwww
mov r0.w, c1
mov oC0, r0
"""),
    # void main(float2 Depth : TEXCOORD0, out float4 Color : COLOR) {
    #   float z = Depth.x / Depth.y; float z2 = z*z; Color = float4(z, z2, 0, 0); }
    ("depth_ps", 0x006CFE38, 152, "main", "p",
     [],
     """ps_2_0
dcl_texcoord0 t0
def c2, 0, 0, 0, 0
rcp r1.x, t0.y
mul r0.x, t0.x, r1.x
mul r0.y, r0.x, r0.x
mov r0.zw, c2
mov oC0, r0
"""),
    # float4x4 g_transform_mat : register(c0); float4 g_floorPos : register(c4);
    # float4x4 g_world : register(c5);
    # Out main(float4 _p : POSITION0, float3 n : NORMAL0):
    #   wp = mul(g_world, _p).xyz; diff = wp - g_floorPos.xyz; screen_pos = mul(g_transform_mat, _p);
    #   normal.xyz = n; normal.w = saturate(g_floorPos.w / length(diff))
    ("floor_vs", 0x006CFFC8, 477, "main", "v",
     [("g_transform_mat", 2, 0, 4), ("g_floorPos", 2, 4, 1), ("g_world", 2, 5, 4)],
     """vs_2_0
dcl_position v0
dcl_normal v1
mul r0, c0, v0.xxxx
mad r0, c1, v0.yyyy, r0
mad r0, c2, v0.zzzz, r0
mad r0, c3, v0.wwww, r0
mov oPos, r0
mul r1, c5, v0.xxxx
mad r1, c6, v0.yyyy, r1
mad r1, c7, v0.zzzz, r1
mad r1, c8, v0.wwww, r1
sub r2.xyz, r1, c4
dp3 r3.x, r2, r2
rsq r3.x, r3.x
mul r4.x, c4.wwww, r3.x
mov oT0.xyz, v1
mov_sat oT0.w, r4.x
"""),
]


def c_array(name, tokens):
    body = []
    for i in range(0, len(tokens), 6):
        body.append("    " + ", ".join("0x%08Xu" % t for t in tokens[i:i + 6]) + ",")
    return "static const uint32_t %s[%d] = {\n%s\n};\n" % (name, len(tokens), "\n".join(body))


def main():
    out = [
        "/* Generated by tools/formats/shaders/gen_rebuilt_shaders.py. Do not edit: change the listings there. */",
        "/* Bytecode for the HLSL sources that VT3.exe compiles at run time and that the HLSL subset",
        " * compiler cannot handle. Each blob has a CTAB comment with its constants. */",
        '#include "d3dx9_compile.h"',
        "",
    ]
    table = []
    for name, src, length, entry, kind, consts, listing in SHADERS:
        tokens, k = sm2_asm.assemble(listing, consts)
        assert k[0] == kind, (name, k, kind)
        out.append(c_array("k_rb_" + name, tokens))
        table.append('    { 0x%08Xu, %uu, "%s", \'%s\', k_rb_%s, %du },'
                     % (src, length, entry, kind, name, len(tokens)))
    out.append("typedef struct rebuilt_entry {")
    out.append("    uint32_t src, src_len;")
    out.append("    const char *entry;")
    out.append("    char kind;                /* 'v' or 'p' */")
    out.append("    const uint32_t *tokens;")
    out.append("    uint32_t ntokens;")
    out.append("} rebuilt_entry;")
    out.append("")
    out.append("static const rebuilt_entry k_rebuilt[] = {")
    out.extend(table)
    out.append("};")
    out.append("")
    out.append("const uint32_t *d3dx_rebuilt_lookup(uint32_t src, uint32_t len, const char *entry, char kind,")
    out.append("                                     uint32_t *ntokens)")
    out.append("{")
    out.append("    for (size_t i = 0; i < sizeof k_rebuilt / sizeof k_rebuilt[0]; i++) {")
    out.append("        const rebuilt_entry *r = &k_rebuilt[i];")
    out.append("        if (r->src == src && r->src_len == len && r->kind == kind && !strcmp(r->entry, entry)) {")
    out.append("            *ntokens = r->ntokens;")
    out.append("            return r->tokens;")
    out.append("        }")
    out.append("    }")
    out.append("    return NULL;")
    out.append("}")
    text = "\n".join(out) + "\n"
    text = text.replace('#include "d3dx9_compile.h"\n', '#include "d3dx9_compile.h"\n\n#include <stddef.h>\n#include <string.h>\n', 1)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", OUT, "with", len(SHADERS), "shaders")
    return 0


if __name__ == "__main__":
    sys.exit(main())
